package com.durable.effect;

/**
 * 一次工具调用对世界造成的影响类别。
 *
 * 区分它们不是洁癖：只读操作可以随便重放，非幂等操作重放一次就是真金白银。
 * 不区分，就只能把所有操作都当危险操作处理 —— 又慢又没必要。
 */
public enum EffectType {

    /** 只读，无副作用。可安全重放无数次。 */
    NONE,

    /** 有副作用但天然幂等（例如「把状态设为 X」）。重放安全。 */
    IDEMPOTENT,

    /** 有副作用且不可逆（例如「创建主机」「扣款」）。**必须走效果账本保护**。 */
    NON_IDEMPOTENT
}
